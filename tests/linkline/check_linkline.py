#!/usr/bin/env python3
"""Compare the plugin's link line to the code that is linked to it.

    python3 tests/linkline/check_linkline.py

Two questions, both of which this repository has answered wrongly before:

1. **Is every library on the link line used by the code?** The analysis found
   thirty linked libraries and thirteen included by `Source/` - a link line is a
   statement about what the binary carries, and sixteen entries were carrying
   nothing. This check reads `target_link_libraries(first ...)` out of
   `CMakeLists.txt` and the `#include` lines out of `Source/`, and asks whether
   each linked target has a caller. A target that does not is either a defect
   (delete it, or link it because the code now uses it) or listed in DEFERRED
   with the plan item that owns it.

2. **Is every `J37_HAS_*` probe read by something?** `Source/DSP/
   OptionalLibraries.h` decides what the build has; a macro that no file outside
   that header reads is a statement about the build nobody checked. xsimd's was
   exactly that, and the `J37_USE_SIMD_TANH` branch it guarded called
   `xsimd::tanh` on a float, which is `std::tanh`.

The include evidence is a spelling table rather than a name match, because the
two spellings genuinely differ for some of these: `nlohmann_json` is included as
`nlohmann/json.hpp`, `pocketfft` as `pocketfft_hdronly.h`, and `chowdsp_simd` is
not included at all - it arrives through `chowdsp_dsp_utils`. A table that says
so is honest; a substring match would silently pass `rack_dsp` because
`PitchTracker.h` contains "rack".

Exit status is 0 only when both questions have no unanswered rows.
"""

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
SOURCE = REPO / "Source"
CMAKE = REPO / "CMakeLists.txt"

# -----------------------------------------------------------------------------
#  What each linked target is spelled like when the code uses it. The values are
#  substrings of an include line under Source/; ANY of them is proof enough.
# -----------------------------------------------------------------------------
SPELLINGS = {
    "chowdsp::chowdsp_dsp_utils": ("chowdsp_dsp_utils/",),
    "chowdsp::chowdsp_math": ("chowdsp_math/",),
    "melatonin_inspector": ("melatonin_inspector/",),
    "melatonin_blur": ("melatonin_blur/",),
    "foleys::foleys_gui_magic": ("foleys_gui_magic/",),
    "xsimd": ("xsimd/",),
    "RTNeural": ("RTNeural/",),
    "readerwriterqueue": ("readerwriterqueue",),
    "glm": ("glm/",),
    "nlohmann_json": ("nlohmann/json.hpp",),
    "pocketfft": ("pocketfft_hdronly.h",),
    # A compiled C library rather than a header: the caller includes its API
    # header, which is <verb.h> because that is the file the library publishes.
    "dattorro_verb": ("verb.h",),
    # Header-only, and reached through the folder the checkout publishes.
    "signalsmith-stretch": ("signalsmith-stretch/",),
}

# -----------------------------------------------------------------------------
#  Targets that are on the link line for a reason other than "a source file
#  includes their headers". Each one has to say what that reason is.
# -----------------------------------------------------------------------------
EXEMPT = {
    "juce::": "JUCE modules: reached through <JuceHeader.h>, which is the module aggregate",
    "PluginResources": "generated by the build (juce_add_binary_data) and reached as <BinaryData.h>",
    "chowdsp::chowdsp_simd": "transitive: included by chowdsp_dsp_utils' own headers, not by Source/",
    "Vulkan::Vulkan": "platform SDK, linked only when J37_RENDER_BACKEND is VULKAN",
    "d3d11": "platform SDK, linked only when the backend is D3D11/D3D12",
    "dxgi": "platform SDK, linked only when the backend is D3D11/D3D12",
    "dxguid": "platform SDK, linked only when the backend is D3D11/D3D12",
    "d3d12": "platform SDK, linked only when the backend is D3D12",
}

# -----------------------------------------------------------------------------
#  Probes whose library is deliberately still linked without a reader, and who
#  owns the decision. A target with a caller but a dead macro is the same defect
#  one level down - xsimd's was exactly this - so the only way past it is a
#  reason and an owner.
# -----------------------------------------------------------------------------
DEFERRED_PROBES = {
    "J37_HAS_CHOWDSP_DSP":
        "plan item 1.1: chowdsp_dsp_utils is the GPLv3 module and no line of the "
        "code branches on whether it is there. Removing it would drop the binary's "
        "GPL obligation, which is the licence decision the plan asks the product "
        "to make rather than a check",
}

#  Where a target goes when it is linked with no caller at all. Empty, and it is
#  meant to stay that way: a library that nothing includes belongs off the link
#  line, not in this dictionary.
DEFERRED = {}


def link_targets():
    """Every token in a target_link_libraries(first ...) call, keywords removed."""
    text = CMAKE.read_text()
    targets = []

    for match in re.finditer(r"target_link_libraries\(\s*first\b", text):
        depth, index = 1, match.end()

        while index < len(text) and depth:
            char = text[index]

            if char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            index += 1

        body = text[match.end():index - 1]
        body = re.sub(r"#[^\n]*", " ", body)                # comments
        body = body.replace("\n", " ")
        body = re.sub(r"\$\{[^}]*\}", " ", body)           # generator expressions

        tokens = body.replace('"', ' ').split()
        skip_next = False

        for token in tokens:
            if skip_next:                                   # the framework after -framework
                skip_next = False
                continue

            if token in ("PRIVATE", "PUBLIC", "INTERFACE") or token.startswith("-"):
                skip_next = token == "-framework"
                continue

            targets.append(token)

    return targets


def includes():
    """Every include line under Source/, as written.

        The probe header (Source/DSP/OptionalLibraries.h) counts here: it includes
        these libraries so the stages do not have to, so its include IS the use
        site for a header that is called through a J37_HAS_* macro. Whether that
        macro is then read by anything is the second question this check asks,
        and it is the one that caught xsimd.
    """
    found = []

    for path in sorted(SOURCE.rglob("*")):
        if path.suffix not in {".h", ".hpp", ".cpp", ".cc", ".mm", ".c"}:
            continue

        for line in path.read_text(errors="replace").splitlines():
            match = re.match(r"\s*#\s*include\s*[<\"]([^>\"]+)[>\"]", line)

            if match:
                found.append((path, match.group(1)))

    return found


def read_probes():
    """The J37_HAS_* macros OptionalLibraries.h decides, and where they are read."""
    library = SOURCE / "DSP" / "OptionalLibraries.h"
    text = library.read_text()
    probed = sorted(set(re.findall(r"#\s*define\s+(J37_HAS_[A-Z0-9_]+)", text)))

    readers = {}

    for macro in probed:
        users = []

        for path in sorted(SOURCE.rglob("*")):
            if path.suffix not in {".h", ".hpp", ".cpp", ".cc", ".mm"} or path == library:
                continue

            body = path.read_text(errors="replace")

            # A mention in a comment is not a reader: the check wants a branch or
            # an expression, so it looks for the macro used outside // and /* */.
            code = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
            code = re.sub(r"//[^\n]*", " ", code)

            if macro in code:
                users.append(path.relative_to(REPO).as_posix())

        readers[macro] = users

    return probed, readers


def main():
    targets = link_targets()
    lines = includes()
    failures = []

    if not targets:
        print("check_linkline: no target_link_libraries(first ...) found in CMakeLists.txt",
              file=sys.stderr)
        return 1

    print(f"check_linkline: {len(targets)} target(s) on the plugin's link line, "
          f"{len(lines)} include line(s) under Source/")

    for target in targets:
        if any(target.startswith(prefix) for prefix in EXEMPT):
            continue

        if target in SPELLINGS:
            if not any(spelling in name for _, name in lines for spelling in SPELLINGS[target]):
                failures.append(
                    f"{target} is linked but no include under Source/ names it "
                    f"(expected one of {', '.join(SPELLINGS[target])})")
            continue

        if target in DEFERRED:
            print(f"  deferred: {target} - {DEFERRED[target]}")
            continue

        failures.append(f"{target} is linked and has no entry in SPELLINGS, EXEMPT or "
                        f"DEFERRED - either the code does not use it, or the check does")

    # The other direction: a header the code includes whose library is not linked
    # is a build that only works while something else drags the target in.
    linked = {target for target in targets}

    for target, spellings in SPELLINGS.items():
        used = any(spelling in name for _, name in lines for spelling in spellings)

        if used and target not in linked:
            failures.append(f"{target} is included by Source/ but is not on the link line")

    probed, readers = read_probes()

    for macro in probed:
        if readers[macro]:
            continue

        if macro in DEFERRED_PROBES:
            print(f"  deferred: {macro} - {DEFERRED_PROBES[macro]}")
            continue

        failures.append(f"{macro} is probed in OptionalLibraries.h and read by nothing "
                        f"outside it - a statement about the build nobody checks")

    print(f"check_linkline: {len(probed)} J37_HAS_* probe(s), "
          f"{sum(1 for macro in probed if readers[macro])} read by real code")

    if failures:
        print()
        for failure in failures:
            print(f"  FAIL {failure}", file=sys.stderr)
        print(f"\ncheck_linkline: {len(failures)} problem(s)", file=sys.stderr)
        return 1

    deferred = sum(1 for macro in probed if macro in DEFERRED_PROBES)
    print(f"check_linkline: every linked library has a caller, every probe is read"
          f"{f' ({deferred} deferred with a reason, named above)' if deferred else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
