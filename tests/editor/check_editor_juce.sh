#!/usr/bin/env bash
#
# Compiles the plugin's own translation units - the processor, the editor and
# every file the editor has been split into - against the REAL JUCE headers,
# with no window, no audio device, no plugin build and no CMake configure.
#
#   tests/editor/check_editor_juce.sh
#
# Why this exists. Source/PluginEditor.cpp and Source/PluginProcessor.cpp are
# being taken apart: a namespace moves to a header, a family of paint routines
# moves to its own .cpp, the declarations stay in the editor's header. Every one
# of those moves is a PURE MOVE of text - the same bytes, in another file - and
# that is exactly what nothing else in the repository checks, because the
# harnesses under tests/ compile extracted *spans* (the DSP, the layout
# arithmetic, the transport rig), never a whole translation unit. A moved block
# whose new file forgets an include, or whose `using` line names a function that
# is not in the header, is textually perfect and does not compile.
#
# So this compiles the whole TUs, and it is the same trick tests/dsp/check_headers_juce.sh
# uses: JUCE is a submodule in the checkout, so a header-only, -fsyntax-only pass
# over real declarations costs seconds and catches everything short of the link.
#
# What it has to stand in for, and why each one is honest:
#
#   JuceHeader.h           The real one is generated by juce_generate_juce_header()
#                          from the target's module list, which is the list this
#                          script repeats below. Same modules, one file, no CMake.
#   BinaryData.h           Generated by juce_add_binary_data from the preset JSON
#                          and the translations, symbol per file. Regenerated here
#                          from the same two directories, with juceaide's own
#                          naming rule ("." and " " become "_"), so the symbols a
#                          TU asks for are the ones the build would have made.
#   FactoryPresetIndex.h   Generated by CMakeLists.txt from FACTORY_PRESET_FILES,
#                          the same list that feeds BinaryData. Same rule again,
#                          sorted the way the preset box is.
#
# The modules below are the plugin's own module list from CMakeLists.txt. The
# third-party include paths are the vendored checkouts in ThirdParty/; the
# libraries that are fetched by CPM (chowdsp, foleys, RTNeural's own cmake, ...)
# are not on the path, so Source/DSP/OptionalLibraries.h probes them off and this
# compiles the build shape without them - the same shape a fresh checkout's
# harnesses compile. That is a stated limitation, not a silent one: this check
# proves the source parses against real JUCE, not that every optional library
# branch compiles.
#
# JUCE_DEBUG is 0, so the melatonin inspector include and the debug-only blocks
# are compiled out - neither is a build without the module vendored. The plugin
# defines that matter are set from the plugin's own CMake target (JucePlugin_Name
# and the four feature flags). JucePlugin_PreferredChannelConfigurations is
# deliberately NOT defined: the processor's constructor initialiser list is
# behind `#ifndef` on it, so defining it would silently compile a different
# constructor, and the error that produced is how this was found.
#
# The list of TUs is not a hand-kept list of the plugin's files: it is every .cpp
# under Source/ that includes PluginEditor.h or PluginProcessor.h. A file the
# editor is split into therefore joins the check by existing, and the guard below
# fails if one of them is missing from the run.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="${HERE}/../.."
JUCE_MODULES="${REPO}/JUCE/modules"
BUILD="${TMPDIR:-/tmp}/j37-editor-check"
CXX="${CXX:-g++}"

if [ ! -d "${JUCE_MODULES}/juce_gui_basics" ]; then
    echo "check_editor_juce: ${JUCE_MODULES} is empty - the JUCE submodule is not" \
         "checked out (git submodule update --init --recursive)" >&2
    exit 1
fi

mkdir -p "${BUILD}/stubs"

# The generated headers, from the same directories the build reads. The naming
# rule is juceaide's (see CMakeLists.txt, which relies on it being the identity
# for these file names): every '.' and ' ' in the file name becomes '_'.
python3 - "${REPO}" "${BUILD}/stubs" <<'PY'
import pathlib
import sys

repo = pathlib.Path(sys.argv[1])
stubs = pathlib.Path(sys.argv[2])

def symbol(name):
    return name.replace(".", "_").replace(" ", "_")

presets = sorted(p.name for p in (repo / "Source/Presets/Factory").glob("*.json"))
translations = sorted(p.name for p in (repo / "Source/Translations").glob("*.txt"))

if not presets or not translations:
    raise SystemExit("check_editor_juce: no resources under Source/Presets/Factory or Source/Translations")

binary = ["#pragma once", "namespace BinaryData", "{"]
for name in presets + translations:
    binary.append(f"    extern const char* {symbol(name)}; extern const int {symbol(name)}Size;")
binary += ["}", ""]
(stubs / "BinaryData.h").write_text("\n".join(binary))

index = ["#pragma once", "",
         "namespace FactoryPresetIndex", "{",
         "    struct Entry { const char* data; int size; };",
         "    inline const Entry entries[] {"]
for name in presets:
    index.append(f"        {{ BinaryData::{symbol(name)}, BinaryData::{symbol(name)}Size }},")
index += ["    };", "}", ""]
(stubs / "FactoryPresetIndex.h").write_text("\n".join(index))
PY

cat > "${BUILD}/stubs/JuceHeader.h" <<'EOF'
// GENERATED by tests/editor/check_editor_juce.sh - do not edit.
// The plugin's module list from CMakeLists.txt, as one header.
#pragma once
#include <juce_audio_basics/juce_audio_basics.h>
#include <juce_audio_devices/juce_audio_devices.h>
#include <juce_audio_formats/juce_audio_formats.h>
#include <juce_audio_processors/juce_audio_processors.h>
#include <juce_audio_utils/juce_audio_utils.h>
#include <juce_box2d/juce_box2d.h>
#include <juce_core/juce_core.h>
#include <juce_cryptography/juce_cryptography.h>
#include <juce_data_structures/juce_data_structures.h>
#include <juce_dsp/juce_dsp.h>
#include <juce_events/juce_events.h>
#include <juce_graphics/juce_graphics.h>
#include <juce_gui_basics/juce_gui_basics.h>
#include <juce_gui_extra/juce_gui_extra.h>
#include <juce_opengl/juce_opengl.h>
EOF

# Every .cpp under Source/ that compiles the processor or the editor, which is
# the set that has to parse. Read from the tree rather than written down.
mapfile -t TUS < <(python3 - "${REPO}" <<'PY'
import pathlib
import sys

repo = pathlib.Path(sys.argv[1])
for path in sorted((repo / "Source").rglob("*.cpp")):
    text = path.read_text(errors="ignore")
    if '#include "PluginEditor.h"' in text or '#include "PluginProcessor.h"' in text:
        print(path.relative_to(repo).as_posix())
PY
)

if [ "${#TUS[@]}" -eq 0 ]; then
    echo "check_editor_juce: no TU under Source/ includes the processor or the editor" >&2
    exit 1
fi

# The include paths, in the order the compiler is given them. The vendored
# third-party checkouts are the ones CMakeLists.txt declares as header-only.
INCLUDES=(
    -I "${REPO}/Source"
    -I "${REPO}/JUCE/modules"
    -I "${BUILD}/stubs"
    -I "${REPO}/ThirdParty/glm"
    -I "${REPO}/ThirdParty/RTNeural"
    -I "${REPO}/ThirdParty/RTNeural/modules/json"
    -I "${REPO}/ThirdParty/nlohmann_json/single_include"
    -I "${REPO}/ThirdParty/xsimd/include"
    -I "${REPO}/ThirdParty/farbot/include"
    -I "${REPO}/ThirdParty/signalsmith-stretch/include"
    -I "${REPO}/ThirdParty/soundtouch/include"
    -I "${REPO}/ThirdParty/pocketfft"
)

# juce_audio_basics pulls juce_core in itself; the module defines are what a
# module header checks before compiling its own sources.
DEFINES=(
    -DJUCE_GLOBAL_MODULE_SETTINGS_INCLUDED=1
    -DJUCE_DEBUG=0
    -DJUCE_DISPLAY_SPLASH_SCREEN=0
    -DJUCE_WEB_BROWSER=0
    -DJUCE_MODULE_AVAILABLE_juce_core=1
    -DJUCE_MODULE_AVAILABLE_juce_events=1
    -DJUCE_MODULE_AVAILABLE_juce_audio_basics=1
    -DJUCE_MODULE_AVAILABLE_juce_audio_formats=1
    -DJUCE_MODULE_AVAILABLE_juce_audio_devices=1
    -DJUCE_MODULE_AVAILABLE_juce_audio_processors=1
    -DJUCE_MODULE_AVAILABLE_juce_audio_utils=1
    -DJUCE_MODULE_AVAILABLE_juce_data_structures=1
    -DJUCE_MODULE_AVAILABLE_juce_dsp=1
    -DJUCE_MODULE_AVAILABLE_juce_graphics=1
    -DJUCE_MODULE_AVAILABLE_juce_gui_basics=1
    -DJUCE_MODULE_AVAILABLE_juce_gui_extra=1
    -DJUCE_MODULE_AVAILABLE_juce_opengl=1
    -DJUCE_MODULE_AVAILABLE_juce_box2d=1
    -DJUCE_MODULE_AVAILABLE_juce_cryptography=1
    -DJUCE_MODULE_AVAILABLE_juce_animation=1
    -DJucePlugin_Name='"J37"'
    -DJucePlugin_IsSynth=0
    -DJucePlugin_WantsMidiInput=0
    -DJucePlugin_ProducesMidiOutput=0
    -DJucePlugin_IsMidiEffect=0
)

# -Wno-cpp: RTNeural warns that its alignment default was taken, which is a
# vendored library's business and not this check's. The source itself is compiled
# with warnings as errors by the platform builds; that is their job, not this
# one's - this one answers "does it still parse".
for tu in "${TUS[@]}"; do
    "${CXX}" -std=c++20 -fsyntax-only -Wno-cpp \
        "${INCLUDES[@]}" "${DEFINES[@]}" "${REPO}/${tu}"
    echo "  ok  ${tu}"
done

# The opt-in hot-path probe's own branch, compiled. `J37_ENABLE_HOTPATH_PROBE` is a
# flag no build defines and no CI job sets, so everything behind it is compiled by
# nobody - and that is exactly how it went two revisions without the counters it
# reads existing at all, and then (found by this pass, on the move that made the
# branch worth compiling) how it held a copy assignment between two atomics. The
# TUs are found by the same rule as the list above: whatever includes the probe's
# header is what has to compile with its flag on.
mapfile -t PROBE_TUS < <(python3 - "${REPO}" <<'PY'
import pathlib
import sys

repo = pathlib.Path(sys.argv[1])
for path in sorted((repo / "Source").rglob("*.cpp")):
    if '#include "HotPathProbe.h"' in path.read_text(errors="ignore"):
        print(path.relative_to(repo).as_posix())
PY
)

for tu in "${PROBE_TUS[@]}"; do
    "${CXX}" -std=c++20 -fsyntax-only -Wno-cpp \
        "${INCLUDES[@]}" "${DEFINES[@]}" -DJ37_ENABLE_HOTPATH_PROBE=1 "${REPO}/${tu}"
    echo "  ok  ${tu} (hot-path probe on)"
done

# The plugin's own headers, each compiled ON ITS OWN. This is the half the TU pass
# above cannot see: a header included by PluginEditor.cpp gets whatever that file
# happened to include first, so a header with a hidden dependency on its includer
# passes there and breaks the first file that includes it the other way round - which
# is exactly what a split produces. The list is the DIRECTORIES, so a header that
# moves in is covered on the next run without being named anywhere; the NativeRenderer
# backends are left out because each one includes its platform's own headers
# (D3D11, Metal, Vulkan), which exist on one operating system each.
#
# BOTH levels are read, and the second one is the reason: splitting the processor put
# Source/ProcessorStateFormat.h and Source/ProcessorPresets.h at the top of Source/
# rather than under Source/GUI/, so a pass that read only Source/GUI/ would have
# compiled neither. The saved-state header is the one that would have hurt - two
# translation units with nothing else in common include it, which is exactly when a
# hidden dependency stops being theoretical.
mapfile -t OWN_HEADERS < <(python3 - "${REPO}/Source" <<'PY'
import pathlib
import sys

source = pathlib.Path(sys.argv[1])

for path in sorted(list(source.glob("*.h")) + list((source / "GUI").glob("*.h"))):
    if path.name.startswith("NativeRenderer"):
        continue
    # Relative to Source/, which is on the include path - the same way the
    # translation units above name them. `Source/PluginProcessor.h` would not
    # resolve from here, and the failure would look like a missing file rather
    # than a wrong spelling.
    print(path.relative_to(source).as_posix())
PY
)

if [ "${#OWN_HEADERS[@]}" -eq 0 ]; then
    echo "check_editor_juce: no headers under Source/ or Source/GUI/" >&2
    exit 1
fi

for header in "${OWN_HEADERS[@]}"; do
    # The plugin's own module header comes first deliberately: a GUI header may rely
    # on juce:: names its includer has already declared (Source/GUI/KnobMetrics.h does
    # exactly that, because tests/layout compiles it with no JUCE at all and a stand-in
    # for the three helpers it asks for - see J37Math.h for the convention). What this
    # step rules out is a dependency on ANOTHER PROJECT header: one that only compiles
    # when the editor's header was included first includes nothing itself, and that is
    # the failure a split produces.
    printf '#include <JuceHeader.h>\n#include "%s"\n' "${header}" > "${BUILD}/header_alone.cpp"
    "${CXX}" -std=c++20 -fsyntax-only -Wno-cpp \
        "${INCLUDES[@]}" "${DEFINES[@]}" "${BUILD}/header_alone.cpp"
    echo "  ok  ${header} (on its own)"
done

echo "check_editor_juce: ${#TUS[@]} translation unit(s) - the processor, the editor" \
     "and every file they are split into, plus ${#PROBE_TUS[@]} of them again with the" \
     "hot-path probe on - and ${#OWN_HEADERS[@]} of the plugin's own header(s) compile" \
     "against real JUCE"
