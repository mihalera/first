#!/usr/bin/env bash
#
# Compiles the stages that have moved into Source/DSP/ against the REAL JUCE
# declarations, with no window, no audio device and no JUCE build.
#
#   tests/dsp/check_headers_juce.sh
#
# Why this exists. The DSP harnesses compile those headers against their own small
# stand-in for juce:: (tests/dsp/shim.h), which is what keeps them seconds of work
# on any machine. That stand-in has to declare whatever a stage touches - and the
# moment a stage MOVES into a header of its own, a name the shim happens to provide
# stops being proof that real JUCE provides it. The failure is one-directional and
# silent until the platform builds run: harness green, plugin red.
#
# So this compiles the same headers against juce_audio_basics itself (and juce_core
# through it), which is the module that owns jmin / jmax / jlimit / MathConstants /
# Decibels / SmoothedValue - the whole of what Source/DSP/ asks for. It is
# -fsyntax-only: no object files, no link, no JUCE build system, and it needs the
# JUCE submodule that the checkout already has.
#
# The header list is READ OUT OF the extractors' own SOURCE_HEADERS lists -
# tests/dsp/extract.py and tests/pitch/extract.py - rather than repeated here, so
# the two cannot drift: a stage added to either list is checked here on the next
# run, with no second place to remember. A header named in neither list is not
# checked at all, which is the one way to miss something: an extractor that moves a
# stage without listing it also stops compiling it, so the harness fails first.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="${HERE}/../.."
JUCE_MODULES="${REPO}/JUCE/modules"
BUILD="${TMPDIR:-/tmp}/j37-juce-header-check"
CXX="${CXX:-g++}"

if [ ! -d "${JUCE_MODULES}/juce_audio_basics" ]; then
    echo "check_headers_juce: ${JUCE_MODULES} is empty - the JUCE submodule is not" \
         "checked out (git submodule update --init --recursive)" >&2
    exit 1
fi

mapfile -t HEADERS < <(python3 - "${HERE}/extract.py" "${HERE}/../pitch/extract.py" <<'PY'
import pathlib
import re
import sys

# The list under test, taken from the extractors rather than retyped: these are
# the headers the harnesses include instead of cutting their text out of
# PluginProcessor.h.
seen: list[str] = []

for path in sys.argv[1:]:
    text = pathlib.Path(path).read_text(encoding="utf-8")
    block = text.split("SOURCE_HEADERS = [", 1)[1].split("]", 1)[0]

    for name in re.findall(r'"([^"]+)"', block):
        if name not in seen:
            seen.append(name)

print("\n".join(seen))
PY
)

if [ "${#HEADERS[@]}" -eq 0 ]; then
    echo "check_headers_juce: no headers in SOURCE_HEADERS (tests/dsp/extract.py,"
         "tests/pitch/extract.py)" >&2
    exit 1
fi

mkdir -p "${BUILD}"
TU="${BUILD}/header_check.cpp"

{
    echo "// GENERATED by tests/dsp/check_headers_juce.sh - do not edit."
    echo "//"
    echo "// The stages that have moved into Source/DSP/, compiled against real JUCE"
    echo "// declarations and then USED, so a declaration that only the harness's"
    echo "// stand-in satisfies fails here rather than in the platform builds."
    echo "#include <juce_audio_basics/juce_audio_basics.h>"
    echo ""

    for header in "${HEADERS[@]}"; do
        echo "#include \"${header}\""
    done

    cat <<'EOF'

[[maybe_unused]] static float probe (float x)
{
    LoudnessMeter meter;
    meter.prepare (48000.0);
    meter.reset();
    const auto window = LoudnessMeter::makeWindowCoefficient (48000.0f);
    x = meter.processFrame (x, x, window);

    TransientShaper shaper;
    x = shaper.process (x, 0.5f, -0.25f, 0.01f, 0.001f, 0.01f);
    shaper.reset();

    GlueCompressor glue;
    const auto coefficients = GlueCompressor::makeCoefficients (48000.0f, 0.01f, 0.2f, 0.0f);
    x = glue.processDetection (x * x, 48000.0f, coefficients);
    x += glue.getEnvelopeActivity() + glue.getTransientAmount();
    glue.reset();

    RateBridge bridge;
    bridge.prepare (44100.0, 192000.0);
    const auto converted = bridge.process (x, [] (float value) { return value * 0.5f; });
    x = converted.wet + converted.dry + static_cast<float> (bridge.delay());
    bridge.reset();

    SaturationCore core;
    core.setWeights (0.25f, 0.25f, 0.25f, 0.25f, 0.25f, 0.25f, 0.25f);
    core.setValveVoice (0);
    core.setAmpVoice (0);
    core.setTransformerVoice (0);
    core.setDigitalVoice (0);
    x = core.process (x, 3.0f, 0.2f);
    x += core.isIdle() ? 0.0f : 1.0f;
    core.reset();

    // The four voice lists are the reason the DSP shim grew a StringArray, so the
    // header that holds them built against the REAL one belongs in this probe: the
    // shim cannot tell a juce::StringArray that takes an add() from one that does
    // not, and the plugin compiles these four in its own translation unit.
    x += static_cast<float> (valveTypeNameList().size() + ampTypeNameList().size()
                           + transformerTypeNameList().size() + digitalTypeNameList().size());

    SubharmonicGenerator sub;
    sub.updateSampleRate (48000.0f);
    sub.nudgeMasterPhase (0.01f);
    x = sub.process (x, 0.5f, 0.5f, 48000.0f);
    x += sub.getTrackedFrequency (48000.0f) * 1.0e-3f;

    PitchTracker tracker;
    tracker.prepare (48000.0);

    for (int n = 0; n < 8; ++n)
        tracker.push (x);

    x += static_cast<float> (tracker.frequency() + tracker.confidence())
       + static_cast<float> (tracker.periodFrames());

    RealtimePitchShifter shifter;
    shifter.reset();
    x = shifter.process (x, 1.05f, 128);
    x += shifter.delayOf (0);

    VinylStage vinyl;
    vinyl.riaaAmount = 0.5f;
    std::uint32_t random = 0x12345678u;
    x = vinyl.process (x, 0, 0.2f, 0.2f, 0.5f, 0.001f, 0.001f, random);

    return x + j37math::exp (1.0f) + j37math::log10 (2.0f) + j37math::sqrt (3.0f);
}

int main()
{
    return probe (0.1f) == 0.0f ? 1 : 0;
}
EOF
} > "${TU}"

# JUCE modules want the project's global settings header, which in a CMake build is
# the generated JuceHeader.h. These defines stand in for it: juce_audio_basics pulls
# juce_core in itself, and nothing here touches a GUI, a device or a file.
"${CXX}" -std=c++17 -fsyntax-only -Wall -Wextra -Wno-unused-parameter \
    -I "${REPO}/Source" -I "${JUCE_MODULES}" \
    -DJUCE_GLOBAL_MODULE_SETTINGS_INCLUDED=1 \
    -DJUCE_MODULE_AVAILABLE_juce_core=1 \
    -DJUCE_MODULE_AVAILABLE_juce_audio_basics=1 \
    -DJUCE_DISPLAY_SPLASH_SCREEN=0 \
    -DJUCE_WEB_BROWSER=0 \
    "${TU}"

echo "check_headers_juce: ${#HEADERS[@]} header(s) from Source/DSP/ compile against" \
     "juce_audio_basics and their public surface instantiates"
