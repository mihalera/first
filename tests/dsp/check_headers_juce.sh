#!/usr/bin/env bash
#
# Compiles the stages that have moved into Source/DSP/ against the REAL JUCE
# declarations, with no window, no audio device and no JUCE build.
#
#   tests/dsp/check_headers_juce.sh
#
# Why this exists. The DSP harnesses compile those headers against their own small
# stand-in for juce:: (tests/dsp/shim.h), which is what keeps them seconds of work
# on any machine. That stand-in has to declare whatever a stage touches - and the
# moment a stage MOVES into a header of its own, a name the shim happens to provide
# stops being proof that real JUCE provides it. The failure is one-directional and
# silent until the platform builds run: harness green, plugin red.
#
# So this compiles the same headers against the real JUCE modules instead, and it
# compiles EACH header's public surface rather than parsing it. What those modules
# are is the directory's own answer, and it is written down here because it changed
# once the IR stage moved in:
#
#   juce_audio_basics   (and juce_core through it) owns jmin / jmax / jlimit /
#                       MathConstants / Decibels / SmoothedValue / StringArray -
#                       everything every other header in Source/DSP/ asks for.
#   juce_audio_formats  owns AudioFormatManager and AudioFormatReader, which the IR
#                       stage opens an impulse-response file with.
#   juce_dsp            owns Convolution, ProcessSpec, AudioBlock and
#                       ProcessContextReplacing, which that stage convolves with.
#
# The two extra modules arrived with Source/DSP/IrStage.h, and the way they arrived
# is the point of reading the DIRECTORY rather than a list: nothing had to remember
# to add it. An IR stage that could not be compiled here would have failed on
# `juce::dsp::Convolution` below, and the answer to that is the module, not a smaller
# header list.
#
# It is -fsyntax-only: no object files, no link, no JUCE build system, and it needs
# the JUCE submodule that the checkout already has.
#
# The list under test is the DIRECTORY: every header in Source/DSP/. It began as the
# extractors' own SOURCE_HEADERS lists, which left one way to miss something - a stage
# that moved into the directory that no harness includes (and no harness cuts any more
# either) would be checked by nobody at all. The directory is the convention, stated in
# Source/DSP/J37Math.h: one concern per header, self-contained, and no JUCE pulled in.
# So anything that moves in is compiled here on the next run without being named
# anywhere, and the probe below is what turns parsing into USE for the stages it has a
# line for.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="${HERE}/../.."
JUCE_MODULES="${REPO}/JUCE/modules"
BUILD="${TMPDIR:-/tmp}/j37-juce-header-check"
CXX="${CXX:-g++}"

if [ ! -d "${JUCE_MODULES}/juce_audio_basics" ]; then
    echo "check_headers_juce: ${JUCE_MODULES} is empty - the JUCE submodule is not" \
         "checked out (git submodule update --init --recursive)" >&2
    exit 1
fi

mapfile -t HEADERS < <(python3 - "${HERE}/../../Source/DSP" <<'PY'
import pathlib
import sys

# Every header in the directory, as the include line the TU below uses.
for path in sorted(pathlib.Path(sys.argv[1]).glob("*.h")):
    print(f"DSP/{path.name}")
PY
)

if [ "${#HEADERS[@]}" -eq 0 ]; then
    echo "check_headers_juce: no headers in Source/DSP/" >&2
    exit 1
fi

mkdir -p "${BUILD}"
TU="${BUILD}/header_check.cpp"

{
    echo "// GENERATED by tests/dsp/check_headers_juce.sh - do not edit."
    echo "//"
    echo "// The stages that have moved into Source/DSP/, compiled against real JUCE"
    echo "// declarations and then USED, so a declaration that only the harness's"
    echo "// stand-in satisfies fails here rather than in the platform builds."
    echo "//"
    echo "// These three are what the directory asks for, and they are included BEFORE the"
    echo "// headers: none of them includes JUCE itself (see Source/DSP/J37Math.h), so the"
    echo "// names they use have to be declared by whoever includes them - here, this file."
    echo "#include <juce_audio_basics/juce_audio_basics.h>"
    echo "#include <juce_audio_formats/juce_audio_formats.h>"
    echo "#include <juce_dsp/juce_dsp.h>"
    echo ""

    for header in "${HEADERS[@]}"; do
        echo "#include \"${header}\""
    done

    cat <<'EOF'

[[maybe_unused]] static float probe (float x)
{
    LoudnessMeter meter;
    meter.prepare (48000.0);
    meter.reset();
    const auto window = LoudnessMeter::makeWindowCoefficient (48000.0f);
    x = meter.processFrame (x, x, window);

    TransientShaper shaper;
    x = shaper.process (x, 0.5f, -0.25f, 0.01f, 0.001f, 0.01f);
    shaper.reset();

    GlueCompressor glue;
    const auto coefficients = GlueCompressor::makeCoefficients (48000.0f, 0.01f, 0.2f, 0.0f);
    x = glue.processDetection (x * x, 48000.0f, coefficients);
    x += glue.getEnvelopeActivity() + glue.getTransientAmount();
    glue.reset();

    RateBridge bridge;
    bridge.prepare (44100.0, 192000.0);
    const auto converted = bridge.process (x, [] (float value) { return value * 0.5f; });
    x = converted.wet + converted.dry + static_cast<float> (bridge.delay());
    bridge.reset();

    // The neural stage in the shape a build WITHOUT RTNeural compiles. Its whole
    // guarded half - the model, the .nam converter, the bridge it drives - lives
    // inside `#if J37_HAS_RTNEURAL` and is compiled by tests/neural/stage_test.cpp
    // against a stand-in for RTNeural's API, not here. What this instantiates is
    // the shape every build without the library has, and it is the one that asks
    // the real JUCE for the two names the harness's shim has been answering so
    // far: juce::String in the loader's own signature, and juce::ignoreUnused in
    // both methods that reduce to nothing without the library. (juce::jlimit, the
    // third name the stage uses, is in the crossfade inside the guarded half, so
    // this build never reaches it.)
    // The IR stage, which no harness renders and which therefore has this as its
    // only automated look. It is also the one header in the directory that needs
    // more than juce_audio_basics, so it is what the two module includes above are
    // for: AudioFormatManager and AudioFormatReader from juce_audio_formats,
    // Convolution / ProcessSpec / AudioBlock / ProcessContextReplacing from juce_dsp.
    // Nothing here touches a file or runs an FFT - the block below is passed
    // through, because no IR has been loaded - it is the SURFACE that is under test.
    IrStage ir;
    juce::dsp::ProcessSpec spec;
    spec.sampleRate = 48000.0;
    spec.maximumBlockSize = 512;
    spec.numChannels = 2;
    ir.prepare (spec);
    juce::AudioBuffer<float> irBuffer (2, 512);
    ir.process (irBuffer, 2, true);
    x += ir.hasIr ? 1.0f : 0.0f;
    x += ir.loadFromFile (juce::File()) ? 1.0f : 0.0f;
    ir.clear();
    ir.reset();

    NeuralStage neural;
    neural.setSampleRates (48000.0, 192000.0);
    x = neural.process (x, 0.5f)
      + (neural.isActive() ? 1.0f : 0.0f)
      + (neural.loadFromJson (juce::String()) ? 1.0f : 0.0f);
    neural.clear();
    neural.reset();

    SaturationCore core;
    core.setWeights (0.25f, 0.25f, 0.25f, 0.25f, 0.25f, 0.25f, 0.25f);
    core.setValveVoice (0);
    core.setAmpVoice (0);
    core.setTransformerVoice (0);
    core.setDigitalVoice (0);
    x = core.process (x, 3.0f, 0.2f);
    x += core.isIdle() ? 0.0f : 1.0f;
    core.reset();

    // The four voice lists are the reason the DSP shim grew a StringArray, so the
    // header that holds them built against the REAL one belongs in this probe: the
    // shim cannot tell a juce::StringArray that takes an add() from one that does
    // not, and the plugin compiles these four in its own translation unit.
    x += static_cast<float> (valveTypeNameList().size() + ampTypeNameList().size()
                           + transformerTypeNameList().size() + digitalTypeNameList().size());

    SubharmonicGenerator sub;
    sub.updateSampleRate (48000.0f);
    sub.nudgeMasterPhase (0.01f);
    x = sub.process (x, 0.5f, 0.5f, 48000.0f);
    x += sub.getTrackedFrequency (48000.0f) * 1.0e-3f;

    InputStage input;
    x = input.processPreamp (x, 0.5f, 0.01f)
      + input.processDistortion (x, 0.2f)
      + input.processDiBox (x, 0.1f, 0.5f, -6.0f, 0.2f, 0.01f, 0.01f, 1.0f);

    PlateReverb plate;
    plate.prepare (48000.0);
    x = plate.process (x, 0, 0.5f, 0.2f);

    ThreeBandEq tone;
    tone.prepare (48000.0f);
    tone.prepareFilters (48000.0f, 30.0f, 18000.0f, 12.0f, 0.7f);
    x = tone.process (x, 0, tone.midBandCoefficient (48000.0f));

    HarmonicAnalyser analyser;
    x += analyser.analyse (x, x * 0.5f, 48000.0f) ? 1.0f : 0.0f;

    TransportRig rig;
    rig.prepare (48000.0);
    rig.beginBlock (0, false, true, 48000.0, 0, 0, 120.0);
    x = rig.platter() + (rig.atSpeed() ? 1.0f : 0.0f);

    RepitchStage repitch;
    repitch.prepare (48000.0);
    std::array<float, 2> frame { x, x };
    repitch.processFrame (frame, 2, 1.0f);
    x = frame[0];
    repitch.reset();

    PitchTracker tracker;
    tracker.prepare (48000.0);

    for (int n = 0; n < 8; ++n)
        tracker.push (x);

    x += static_cast<float> (tracker.frequency() + tracker.confidence())
       + static_cast<float> (tracker.periodFrames());

    RealtimePitchShifter shifter;
    shifter.reset();
    x = shifter.process (x, 1.05f, 128);
    x += shifter.delayOf (0);

    VinylStage vinyl;
    vinyl.riaaAmount = 0.5f;
    std::uint32_t random = 0x12345678u;
    x = vinyl.process (x, 0, 0.2f, 0.2f, 0.5f, 0.001f, 0.001f, random);

    return x + j37math::exp (1.0f) + j37math::log10 (2.0f) + j37math::sqrt (3.0f);
}

int main()
{
    return probe (0.1f) == 0.0f ? 1 : 0;
}
EOF
} > "${TU}"

# JUCE modules want the project's global settings header, which in a CMake build is
# the generated JuceHeader.h. These defines stand in for it: juce_audio_basics pulls
# juce_core in itself, and nothing here touches a GUI, a device or a file.
"${CXX}" -std=c++17 -fsyntax-only -Wall -Wextra -Wno-unused-parameter \
    -I "${REPO}/Source" -I "${JUCE_MODULES}" \
    -DJUCE_GLOBAL_MODULE_SETTINGS_INCLUDED=1 \
    -DJUCE_MODULE_AVAILABLE_juce_core=1 \
    -DJUCE_MODULE_AVAILABLE_juce_events=1 \
    -DJUCE_MODULE_AVAILABLE_juce_audio_basics=1 \
    -DJUCE_MODULE_AVAILABLE_juce_audio_formats=1 \
    -DJUCE_MODULE_AVAILABLE_juce_dsp=1 \
    -DJUCE_DISPLAY_SPLASH_SCREEN=0 \
    -DJUCE_WEB_BROWSER=0 \
    "${TU}"

echo "check_headers_juce: ${#HEADERS[@]} header(s) from Source/DSP/ compile against" \
     "juce_audio_basics, juce_audio_formats and juce_dsp, and their public surface" \
     "instantiates"
