#!/usr/bin/env python3
"""Embed a SPIR-V binary (or a GLSL source file used as a placeholder for CI) as a
C array header for the Vulkan renderer.

Usage for a real SPIR-V file:
    python3 cmake/VulkanEmbedSpv.py \
        --input path/to/shader.vert.spv \
        --header path/to/shader_vert_spirv.h \
        --symbol shader_vert

Usage for a GLSL source placeholder (CI when glslangValidator is not present):
    python3 cmake/VulkanEmbedSpv.py \
        --input path/to/shader.vert.glsl \
        --header path/to/shader_vert_spirv.h \
        --symbol shader_vert

If the input file has a .spv extension, the file is treated as SPIR-V and must be
a multiple of 4 bytes; the header gets a real embedded array plus
*_spirv_words = bytes/4.

If the input file has any other extension (for example .vert.glsl or .frag.glsl),
the file is treated as a GLSL source placeholder used only so the Vulkan shader
plumbing can still be exercised without the validator. The emitted header still
contains the extern declarations, but the array is empty and *_spirv_words is 0,
with a comment saying the SPIR-V was not available.

This is a build tool, not part of the shipped source.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path


def read_bytes(path: Path) -> bytes:
    return path.read_bytes()


def to_c_array(name: str, data: bytes, placeholder: bool, input: Path) -> str:
    lines: list[str] = []
    lines.append("// Generated by VulkanEmbedSpv.py from %s" % input.name)
    lines.append("// Do not edit by hand. SPIR-V embedded as a C array.")
    if placeholder:
        lines.append("// NOTE: no SPIR-V was available; the array below is empty "
                     "and is a placeholder for CI only.")
    lines.append("#pragma once")
    lines.append("#include <stddef.h>")
    lines.append("extern const unsigned char %s[];" % (name,))
    lines.append("extern const unsigned int %s_words;" % (name,))
    lines.append("")
    lines.append("// Definitions.")
    lines.append("static const unsigned char %s[] = {" % (name,))
    if placeholder:
        lines.append("    // No SPIR-V bytes available for this stage in this build.")
    else:
        for offset in range(0, len(data), 16):
            chunk = data[offset:offset + 16]
            lines.append("    " + ", ".join("0x%02x" % byte for byte in chunk) + ",")
    lines.append("};")
    lines.append("static const unsigned int %s_words = %d;" %
                 (name, len(data) // 4 if not placeholder else 0))
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Embed a SPIR-V binary (or GLSL placeholder) as a generated C header.")
    parser.add_argument("--input", required=True, type=Path,
                        help="Path to the SPIR-V binary, or a GLSL source placeholder.")
    parser.add_argument("--header", required=True, type=Path,
                        help="Path to the generated C header to write.")
    parser.add_argument("--symbol", required=True,
                        help="C symbol prefix for the embedded array.")
    args = parser.parse_args(argv)

    if not args.input.exists():
        print("VulkanEmbedSpv: input not found: %s" % args.input, file=sys.stderr)
        return 1

    placeholder = args.input.suffix != ".spv"
    data = read_bytes(args.input)

    if not placeholder and len(data) % 4 != 0:
        print("VulkanEmbedSpv: SPIR-V word size check failed: %s is %d bytes "
              "(not a multiple of 4)" % (args.input, len(data)),
              file=sys.stderr)
        return 1

    header = to_c_array(args.symbol, data, placeholder=placeholder, input=args.input)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding='utf-8')
    print("VulkanEmbedSpv: wrote %s (%sbytes, placeholder=%s)" %
          (args.header, len(data), placeholder))
    return 0


if __name__ == "__main__":
    sys.exit(main())
